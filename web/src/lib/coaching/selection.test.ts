import assert from "node:assert/strict";
import test from "node:test";
import type { GameCore, PlayerLine } from "@/lib/analytics/types";
import { game } from "./test-fixtures";
import { buildSelectionAdvice, SELECTION_WEIGHTS, type SelectionCandidate, type SelectionWorkload } from "./selection";
import type { GamePlan } from "./game-plan";

// The advisor's contract, exercised without a database - the same style as game-plan.test.ts.
//
// Every fixture below is a plain object: a squad with meta, a season of GameCores, and (where the
// test needs it) a hand-built GamePlan. The tests that matter most are the degradation ones - a
// matchup score that silently became 0 instead of null would quietly bench every player on a squad
// whose positions are not recorded, which is the exact failure mode the roadmap called out.

const MINUTES = 30;

const star = (): Partial<PlayerLine> => ({
  minutesPlayed: MINUTES, points: 26, fieldGoalsMade: 10, fieldGoalsAttempted: 15, freeThrowsMade: 5, freeThrowsAttempted: 6,
  threePointsMade: 1, threePointsAttempted: 3, assists: 7, rebounds: 9, steals: 2, blocks: 1, turnovers: 1, fouls: 1,
});

const poor = (): Partial<PlayerLine> => ({
  minutesPlayed: MINUTES, points: 4, fieldGoalsMade: 1, fieldGoalsAttempted: 12, freeThrowsMade: 2, freeThrowsAttempted: 6,
  threePointsMade: 0, threePointsAttempted: 3, assists: 0, rebounds: 2, steals: 0, blocks: 0, turnovers: 4, fouls: 5,
});

const steady = (): Partial<PlayerLine> => ({
  minutesPlayed: MINUTES, points: 12, fieldGoalsMade: 4, fieldGoalsAttempted: 10, freeThrowsMade: 3, freeThrowsAttempted: 4,
  threePointsMade: 1, threePointsAttempted: 3, assists: 3, rebounds: 5, steals: 1, blocks: 0, turnovers: 2, fouls: 2,
});

const guard = (id: string, overrides: Partial<SelectionCandidate> = {}): SelectionCandidate => ({
  playerId: id, name: id.toUpperCase(), jerseyNumber: null, position: "Point guard", heightCm: 185, ...overrides,
});

function matchday(ours: { id: string; stat: Partial<PlayerLine> }[], opps: { id: string; stat: Partial<PlayerLine> }[]): GameCore {
  return game(
    { id: "US", players: ours.map((p) => ({ id: p.id, stat: p.stat })) },
    { id: "OPP", players: opps.map((p) => ({ id: p.id, stat: p.stat })) },
  );
}

// Six games in a row; `ours` describes who played each game by index.
function season(ours: { id: string; stat: Partial<PlayerLine> }[][], oppIds: string[] = ["opp1", "opp2", "opp3"]): GameCore[] {
  return ours.map((lineup) => matchday(lineup, oppIds.map((id) => ({ id, stat: steady() }))));
}

const SIX = (stat: (_id: string) => Partial<PlayerLine>) =>
  Array.from({ length: 6 }, () => ["us1", "us2", "us3", "us4", "us5"].map((id) => ({ id, stat: stat(id) })));

// `now` is derived from the season itself: the fixtures' dates are generated by the shared test
// fixtures and would otherwise drift out of a hardcoded load window as more tests run.
const after = (games: GameCore[]) =>
  new Date(Math.max(...games.map((g) => new Date(g.scheduledAt).getTime())) + 24 * 60 * 60 * 1000);

function planFor(assignments: GamePlan["assignments"], overrides: Partial<GamePlan> = {}): GamePlan {
  return {
    focus: { seasonClubId: "US", name: "Us", games: 6 },
    opponent: { seasonClubId: "OPP", name: "Opponent", games: 6 },
    status: "OK",
    insufficientReason: null,
    keys: [],
    howTheyBeatUs: [],
    assignments,
    lateGame: null,
    headToHead: { games: 0, focusWins: 0, focusLosses: 0, results: [] },
    defenseNote: "",
    ...overrides,
  };
}

test("form ranks a high-output player above a low-output one, using the last five games", () => {
  const games = season(SIX((id) => (id === "us1" ? star() : id === "us2" ? poor() : steady())));
  const advice = buildSelectionAdvice({
    games,
    squad: ["us1", "us2", "us3"].map((id) => guard(id)),
    now: after(games),
  });

  assert.equal(advice.status, "OK");
  const [first, , last] = advice.candidates;
  assert.equal(first.playerId, "us1");
  assert.equal(last.playerId, "us2");
  assert.ok(first.formScore > last.formScore, `expected us1 ${first.formScore} > us2 ${last.formScore}`);
  assert.equal(first.recommendation, "START");

  // The form evidence is explicit about what was measured and over how many games.
  const form = advice.candidates[0].evidence[0];
  assert.match(form.metric, /last 5 games/);
  assert.equal(form.sample.games, 5);
  assert.equal(form.source, "BOX_SCORE");
});

test("form ignores games older than the five-game window", () => {
  // us1: five great early games then five bad ones; us2 steady throughout. Season totals favour us1,
  // the window favours us2 - and the window is what the advisor is specified to use.
  const games: GameCore[] = [];
  for (let i = 0; i < 10; i += 1) {
    const us1Stat = i < 5 ? star() : poor();
    games.push(matchday(
      [{ id: "us1", stat: us1Stat }, { id: "us2", stat: steady() }, { id: "us3", stat: steady() }],
      [{ id: "opp1", stat: steady() }, { id: "opp2", stat: steady() }, { id: "opp3", stat: steady() }],
    ));
  }
  const advice = buildSelectionAdvice({
    games,
    squad: [guard("us1"), guard("us2"), guard("us3")],
    now: after(games),
  });

  const us1 = advice.candidates.find((c) => c.playerId === "us1")!;
  const us2 = advice.candidates.find((c) => c.playerId === "us2")!;
  assert.ok(us2.formScore > us1.formScore, `us2 (steady) ${us2.formScore} should beat us1 (poor recently) ${us1.formScore}`);
});

test("a missing game plan leaves matchup null and renormalizes the overall score over the other components", () => {
  const games = season(SIX((id) => (id === "us1" ? star() : steady())));
  const advice = buildSelectionAdvice({
    games,
    squad: [guard("us1"), guard("us2"), guard("us3")],
    plan: null,
    now: after(games),
  });

  const candidate = advice.candidates[0];
  assert.equal(candidate.matchupScore, null);
  assert.equal(candidate.matchupState, "INSUFFICIENT_DATA");
  assert.equal(advice.matchupState, "INSUFFICIENT_DATA");
  assert.ok(advice.notes.some((n) => /Matchup is excluded/.test(n)));

  // Exact renormalization: matchup's 0.3 weight is removed, not filled with a zero score.
  const weightSum = SELECTION_WEIGHTS.form + SELECTION_WEIGHTS.availability + SELECTION_WEIGHTS.load;
  const expected = Math.round(
    (candidate.formScore * SELECTION_WEIGHTS.form + candidate.availabilityScore * SELECTION_WEIGHTS.availability + candidate.loadScore * SELECTION_WEIGHTS.load) / weightSum,
  );
  assert.equal(candidate.overallScore, expected);
});

test("matchup: an assigned defender outranks an unassigned one, and a position match adds to the score", () => {
  const games = season(SIX((id) => (id === "us1" ? star() : steady())));
  const plan = planFor([
    {
      threat: { playerId: "opp1", name: "Threat One", jerseyNumber: 7, ppg: 18, position: "Point guard" },
      defender: { playerId: "us1", name: "US1", jerseyNumber: 1, position: "Point guard" },
      reasons: ["best perimeter defender"],
      alternatives: [],
    },
    {
      threat: { playerId: "opp2", name: "Threat Two", jerseyNumber: 8, ppg: 12, position: "Point guard" },
      defender: null,
      reasons: [],
      alternatives: [],
    },
  ]);

  const advice = buildSelectionAdvice({
    games,
    squad: [guard("us1", { jerseyNumber: 1 }), guard("us2", { jerseyNumber: 2 }), guard("us3", { jerseyNumber: 3 })],
    plan,
    now: after(games),
  });
  assert.equal(advice.matchupState, "OK");
  const us1 = advice.candidates.find((c) => c.playerId === "us1")!;
  const us3 = advice.candidates.find((c) => c.playerId === "us3")!;
  assert.equal(us1.matchupState, "OK");
  assert.ok(us1.matchupScore! >= 80, `assigned + position match + 18 ppg should be a high score, got ${us1.matchupScore}`);
  assert.ok(us1.matchupScore! > us3.matchupScore!, "an assigned defender must out-score an unassigned one on matchup");
});

test("matchup degrades to assignments-only when the opponent's threat positions are not recorded", () => {
  const games = season(SIX((id) => (id === "us1" ? star() : steady())));
  const plan = planFor([
    {
      threat: { playerId: "opp1", name: "Threat One", jerseyNumber: 7, ppg: 15, position: null },
      defender: { playerId: "us1", name: "US1", jerseyNumber: 1, position: "Point guard" },
      reasons: [],
      alternatives: [],
    },
  ]);

  const advice = buildSelectionAdvice({ games, squad: [guard("us1", { jerseyNumber: 1 }), guard("us2")], plan, now: after(games) });
  assert.equal(advice.matchupState, "DEGRADED");
  const us1 = advice.candidates.find((c) => c.playerId === "us1")!;
  assert.notEqual(us1.matchupScore, null, "a degraded matchup still produces a number");
  assert.ok(advice.notes.some((n) => /assignments only/.test(n)));
});

test("a squad with no recorded positions gets no matchup score at all", () => {
  const games = season(SIX((id) => (id === "us1" ? star() : steady())));
  const plan = planFor([
    {
      threat: { playerId: "opp1", name: "Threat One", jerseyNumber: 7, ppg: 15, position: "Point guard" },
      defender: null,
      reasons: [],
      alternatives: [],
    },
  ]);
  const noPositions = ["us1", "us2", "us3"].map((id) => guard(id, { position: "Unknown", heightCm: 0 }));
  const advice = buildSelectionAdvice({ games, squad: noPositions, plan, now: after(games) });

  assert.equal(advice.matchupState, "INSUFFICIENT_DATA");
  assert.ok(advice.candidates.every((c) => c.matchupScore === null));
  assert.deepEqual(advice.squadPositionCoverage, { usable: 0, total: 3 });
  assert.ok(advice.notes.some((n) => /no recorded position/.test(n)));
});

test("availability rewards foul discipline and load rewards freshness", () => {
  // us1 plays every game and fouls heavily; us2 appears only in the last game.
  const games: GameCore[] = [];
  for (let i = 0; i < 6; i += 1) {
    const lineup = [{ id: "us1", stat: poor() }, { id: "us3", stat: steady() }];
    if (i === 5) lineup.push({ id: "us2", stat: steady() });
    games.push(matchday(lineup, [{ id: "opp1", stat: steady() }, { id: "opp2", stat: steady() }, { id: "opp3", stat: steady() }]));
  }

  const advice = buildSelectionAdvice({
    games,
    squad: [guard("us1"), guard("us2"), guard("us3")],
    now: after(games),
  });
  const us1 = advice.candidates.find((c) => c.playerId === "us1")!;
  const us2 = advice.candidates.find((c) => c.playerId === "us2")!;
  assert.ok(us2.loadScore > us1.loadScore, `fewer recent games must score higher on load: ${us2.loadScore} vs ${us1.loadScore}`);
  assert.ok(us2.availabilityScore > us1.availabilityScore, `fewer fouls must score higher on availability: ${us2.availabilityScore} vs ${us1.availabilityScore}`);
});

test("reported workload lowers the load score, and its evidence says so", () => {
  const games = season(SIX(() => steady()));
  const workload: SelectionWorkload[] = [{ playerId: "us1", minutesLast7Days: 240, gamesLast7Days: 7 }];
  const advice = buildSelectionAdvice({ games, squad: [guard("us1"), guard("us2")], workload, now: after(games) });

  const us1 = advice.candidates.find((c) => c.playerId === "us1")!;
  const us2 = advice.candidates.find((c) => c.playerId === "us2")!;
  assert.ok(us1.loadScore < us2.loadScore);
  const evidence = us1.evidence.find((e) => /Recent load/.test(e.metric))!;
  assert.match(evidence.sample.label, /reported minutes/);
  assert.equal(evidence.confidence, "HIGH");
});

test("recommendations are rank-based: five starters, three rotation, then bench", () => {
  const ids = ["p1", "p2", "p3", "p4", "p5", "p6", "p7", "p8", "p9"];
  const games = season(
    Array.from({ length: 6 }, (_, g) =>
      ids.map((id, i) => ({ id, stat: i === 0 && g < 5 ? star() : i === 1 ? poor() : steady() })),
    ),
    ["opp1", "opp2", "opp3"],
  );
  const advice = buildSelectionAdvice({
    games,
    squad: ids.map((id) => guard(id)),
    now: after(games),
  });

  assert.equal(advice.starterCount, 5);
  assert.deepEqual(advice.candidates.map((c) => c.recommendation), [
    "START", "START", "START", "START", "START", "ROTATE", "ROTATE", "ROTATE", "BENCH",
  ]);
});

test("whyNot explains the next-ranked player and is null for the last one", () => {
  const games = season(SIX((id) => (id === "us1" ? star() : id === "us2" ? poor() : steady())));
  const advice = buildSelectionAdvice({ games, squad: [guard("us1"), guard("us2"), guard("us3")], now: after(games) });

  const [first, second, last] = advice.candidates;
  assert.ok(first.whyNot && first.whyNot.includes(second.name), "whyNot must name the next-ranked player");
  assert.match(first.whyNot!, /overall/);
  assert.equal(second.whyNot?.includes(last.name), true);
  assert.equal(last.whyNot, null, "the bottom-ranked player has no next to be preferred over");
});

test("with no recorded games the advice says INSUFFICIENT_DATA instead of inventing a ranking", () => {
  const advice = buildSelectionAdvice({ games: [], squad: [guard("us1"), guard("us2")], now: new Date(Date.UTC(2026, 8, 8)) });
  assert.equal(advice.status, "INSUFFICIENT_DATA");
  assert.ok(advice.insufficientReason);
  assert.ok(advice.candidates.every((c) => c.formScore === 0));
  assert.ok(advice.notes.some((n) => /No player has a qualifying sample/.test(n)));
  assert.equal(advice.candidates.length, 2, "a coach still sees the whole squad");
});

test("an empty squad returns no candidates and no coverage claim", () => {
  const advice = buildSelectionAdvice({ games: [], squad: [], now: new Date(Date.UTC(2026, 8, 8)) });
  assert.equal(advice.status, "INSUFFICIENT_DATA");
  assert.equal(advice.squadPositionCoverage, null);
  assert.deepEqual(advice.candidates, []);
  assert.equal(advice.starterCount, 0);
});

test("a plan whose status is INSUFFICIENT_DATA is treated as no plan", () => {
  const games = season(SIX((id) => (id === "us1" ? star() : steady())));
  const plan = planFor(
    [{ threat: { playerId: "opp1", name: "T", jerseyNumber: 1, ppg: 10, position: "Point guard" }, defender: null, reasons: [], alternatives: [] }],
    { status: "INSUFFICIENT_DATA", insufficientReason: "2 opponent games" },
  );
  const advice = buildSelectionAdvice({ games, squad: [guard("us1"), guard("us2")], plan, now: after(games) });
  assert.equal(advice.matchupState, "INSUFFICIENT_DATA");
  assert.ok(advice.candidates.every((c) => c.matchupScore === null));
});
